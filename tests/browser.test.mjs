import {chromium} from '@playwright/test';
import assert from 'node:assert/strict';
import {mkdir} from 'node:fs/promises';
const browser=await chromium.launch({headless:true,executablePath:process.env.FIELD_SHIFT_BROWSER||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
await mkdir('qa',{recursive:true});
const page=await browser.newPage({viewport:{width:1440,height:1100},deviceScaleFactor:1});
page.setDefaultTimeout(30000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
// Keep visual checks deterministic; NASA's saved numerical and imagery data remain real.
await page.route('https://fonts.googleapis.com/**',r=>r.abort());
await page.goto('http://127.0.0.1:5173',{waitUntil:'domcontentloaded'});
await page.locator('.rotation-card').first().waitFor({timeout:45000});
assert.equal(await page.locator('.rotation-card').count(),3);
assert.match(await page.locator('#status').innerText(),/20 complete calendar years.*19 complete/);
assert.match(await page.locator('#climate-variability').innerText(),/year-to-year variability/);
assert.match(await page.locator('.metric-foot').innerText(),/highest daily maximum/);
await page.locator('#ph').fill('11');await page.locator('#ph').dispatchEvent('change');
await page.waitForFunction(()=>document.querySelector('#export').disabled);
assert.equal(await page.locator('#input-status').isVisible(),true);
assert.equal(await page.locator('#ph').getAttribute('aria-invalid'),'true');
await page.locator('#ph').fill('');await page.locator('#ph').dispatchEvent('change');
await page.waitForFunction(()=>!document.querySelector('#export').disabled);
assert.equal(await page.locator('#input-status').isVisible(),false);
const before=await page.locator('[data-rotation="baseline"] .score-circle').innerText();
await page.locator('#scenario-rain').fill('-30');
await page.locator('#scenario-rain').dispatchEvent('input');
await page.waitForFunction(()=>document.querySelector('#scenario-label').textContent.includes('-30%'));
const after=await page.locator('[data-rotation="baseline"] .score-circle').innerText();
assert.notEqual(before,after);
await page.locator('[data-detail="best"]').click();
await page.locator('dialog').waitFor({state:'visible'});
assert.match(await page.locator('#dialog-body').innerText(),/19 complete June/);
await page.locator('.replay-table summary').click();
assert.equal(await page.locator('.replay-table tbody tr').count(),19);
await page.keyboard.press('Escape');
await page.locator('#reset-scenario').click();
await page.waitForFunction(()=>document.querySelector('#scenario-label').textContent.includes('historical climate'));
await page.locator('[data-chart="temp"]').click();
assert.match(await page.locator('#chart-unit').innerText(),/temperature/);
await page.locator('#history-table').click();
assert.equal(await page.locator('dialog tbody tr').count(),20);
await page.keyboard.press('Escape');
await page.locator('[data-chart="rain"]').click();
await page.locator('#crop-0').selectOption('millet');
await page.waitForFunction(()=>document.querySelector('[data-rotation="baseline"]').textContent.includes('Pearl millet'));
await page.locator('#crop-0').selectOption('rice');
await page.waitForFunction(()=>document.querySelector('[data-rotation="baseline"]').textContent.includes('Rice'));
await page.locator('[data-open="sources"]').first().click();
assert.equal(await page.locator('.resource-row').count(),25);
assert.match(await page.locator('#dialog-body').innerText(),/not active integrations/);
await page.keyboard.press('Escape');
const downloadPromise=page.waitForEvent('download');await page.locator('#export').click();
const download=await downloadPromise;assert.equal(download.suggestedFilename(),'field-shift-rotation-report.html');
await download.saveAs('qa/export-report.html');
// Simulate a NASA outage: existing results must remain tied to the old location.
await page.route('https://power.larc.nasa.gov/**',r=>r.fulfill({status:503,body:'Service unavailable'}));
await page.locator('#latitude').fill('15.500');await page.locator('#longitude').fill('75.500');
await page.locator('#load-climate').click();
await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('HTTP 503'));
assert.match(await page.locator('#location-name').innerText(),/Bengaluru/);
assert.match(await page.locator('#status').innerText(),/Results still describe Bengaluru/);
await page.locator('#latitude').fill('12.970');await page.locator('#longitude').fill('77.600');await page.locator('#load-climate').click();
await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('Saved NASA response'));
await page.waitForTimeout(700);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
await page.screenshot({path:'qa/desktop.png',fullPage:true});
await page.setViewportSize({width:390,height:844});await page.waitForTimeout(500);
assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth),false);
await page.screenshot({path:'qa/mobile.png',fullPage:true});
assert.equal(errors.length,0,errors.join('\n'));
await browser.close();console.log('Browser checks passed: desktop/mobile layout, scenarios, baseline changes, evidence, table, export, and NASA failure handling.');
