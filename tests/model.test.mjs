import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {summarize,recommend,scoreRotation,powerUrl,slope,distribution,CROPS} from '../dist/model.js';
const raw=JSON.parse(readFileSync(new URL('../dist/data/bengaluru-power.json',import.meta.url)));
const climate=summarize(raw);
const settings={soil:'loam',ph:'',irrigation:0,rotation:['rice','maize','fallow'],weights:{water:40,soil:30,income:10,risk:20}};
assert.equal(climate.annual.length,20);
assert.equal(climate.rotations.length,19);
assert.equal(climate.rotations[0].year,2006);
assert.equal(climate.rotations.at(-1).year,2024);
assert.equal(climate.rotations[0].seasons[1].days[0].date,'20061001');
assert.equal(climate.rotations[0].seasons[1].days.at(-1).date,'20070131');
assert.equal(climate.rotations[1].seasons[2].days.length,121);
assert.ok(climate.rain>0&&climate.rain<4000);
assert.ok(climate.temp>0&&climate.temp<50);
assert.equal(slope([[1,2],[2,4],[3,6]]),2);
assert.deepEqual(distribution([0,0,0]),{min:0,max:0,sd:0,cv:null});
const spread=distribution([10,20]);
assert.equal(spread.sd,5);assert.equal(spread.min,10);assert.equal(spread.max,20);
assert.ok(Math.abs(spread.cv-100/3)<1e-10);
assert.equal(distribution([null,NaN]).cv,null);
assert.equal(climate.peak,Math.max(...Object.values(raw.properties.parameter.T2M_MAX).filter(v=>v!==-999)));
assert.ok(climate.rainStats.min<climate.rain&&climate.rainStats.max>climate.rain);
assert.ok(climate.rainStats.cv>0);
const damaged=structuredClone(raw);damaged.properties.parameter.PRECTOTCORR['20100603']=-999;
const missing=summarize(damaged);
assert.equal(missing.missingDays,1);
assert.equal(missing.annual.length,19);
assert.equal(missing.rotations.length,18);
assert.ok(!missing.rotations.some(y=>y.year===2010));
const absent=structuredClone(raw);delete absent.properties.parameter.PRECTOTCORR['20100603'];
assert.equal(summarize(absent).missingDays,1,'An omitted day is missing even without an explicit fill value.');
assert.throws(()=>summarize({properties:{parameter:{}}}),/missing/);
assert.throws(()=>powerUrl(91,0),/valid latitude/);
assert.throws(()=>powerUrl(0,181),/valid latitude/);
assert.throws(()=>powerUrl(NaN,0),/valid latitude/);
assert.ok(powerUrl(12.97,77.6).includes('GWETROOT'));
const base=scoreRotation(settings.rotation,climate,settings);
const drier=scoreRotation(settings.rotation,climate,settings,{rain:-30,temp:0});
const wetter=scoreRotation(settings.rotation,climate,settings,{rain:30,temp:0});
const irrigated=scoreRotation(settings.rotation,climate,{...settings,irrigation:350});
assert.ok(drier.deficit>=base.deficit);
assert.ok(wetter.deficit<=base.deficit);
assert.ok(irrigated.deficit<=base.deficit);
assert.ok(drier.scores.water<=base.scores.water);
assert.ok(drier.covered<=base.covered);
assert.equal(base.parts[2].need,0);
assert.equal(base.parts[2].rain,0);
assert.ok(base.parts[0].rain<climate.seasons[0].rain);
assert.equal(base.yearly.length,19);
assert.ok(base.covered<=base.yearly.length);
const equal=scoreRotation(settings.rotation,climate,{...settings,weights:{water:0,soil:0,income:0,risk:0}});
assert.ok(Number.isFinite(equal.score));
assert.ok(Math.abs(equal.score-Object.values(equal.scores).reduce((a,b)=>a+b,0)/5)<1e-8);
console.time('Exhaustive rotation comparison');
const result=recommend(climate,settings);
console.timeEnd('Exhaustive rotation comparison');
assert.deepEqual(result.baseline.ids,settings.rotation);
assert.notDeepEqual(result.best.ids,result.alternate.ids);
assert.notDeepEqual(result.best.ids,settings.rotation);
assert.ok(result.count>100);
const plans=[result.baseline,result.best,result.alternate,result.soil,result.climate];
assert.equal(new Set(plans.map(r=>r.ids.join())).size,5,'All five plan categories must be unique.');
for(const r of plans){
  assert.ok(r.score>=0&&r.score<=100);
  for(const value of Object.values(r.scores))assert.ok(value>=0&&value<=100);
  assert.equal(r.yearly.length,19);
  assert.ok(r.covered+r.severe<=r.yearly.length);
}
assert.ok(result.best.feasible&&result.alternate.feasible);
assert.ok(result.soil.feasible&&result.climate.feasible);
for(let i=2;i<plans.length;i++)for(let j=0;j<i;j++)assert.ok(plans[i].ids.filter((id,k)=>id!==plans[j].ids[k]).length>=2,'The example has enough alternatives to change at least two seasons.');
const other=recommend(climate,{...settings,rotation:['fallow','fallow','fallow'],soil:'sandy',ph:4.5,irrigation:150,weights:{water:0,soil:0,income:0,risk:0}},{rain:-30,temp:3});
assert.deepEqual(other.baseline.ids,['fallow','fallow','fallow'],'Even an excluded baseline remains visible.');
assert.equal(new Set(['baseline','best','alternate','soil','climate'].map(k=>other[k].ids.join())).size,5);
for(const key of ['best','alternate','soil','climate'])assert.ok(other[key].feasible&&Number.isFinite(other[key].score));
assert.equal(CROPS.length,13);
console.log(JSON.stringify({tests:'passed',annualYears:climate.annual.length,rotationYears:climate.rotations.length,rain:climate.rain,temp:climate.temp,wetness:climate.wet,candidates:result.count,best:result.best.ids,alternate:result.alternate.ids,baselineDeficit:base.deficit},null,2));
